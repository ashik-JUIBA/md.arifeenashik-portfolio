export function getStoredBlogPosts(): BlogPost[] {
  if (typeof window === "undefined") return INITIAL_BLOG_POSTS;
  const stored = localStorage.getItem("ashik_blog_posts");
  if (stored) {
    try {
      return JSON.parse(stored);
    } catch {
      return INITIAL_BLOG_POSTS;
    }
  }
  localStorage.setItem("ashik_blog_posts", JSON.stringify(INITIAL_BLOG_POSTS));
  return INITIAL_BLOG_POSTS;
}

export function saveBlogPosts(posts: BlogPost[]): void {
  if (typeof window !== "undefined") {
    localStorage.setItem("ashik_blog_posts", JSON.stringify(posts));
  }
}
